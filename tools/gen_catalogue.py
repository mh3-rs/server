#!/usr/bin/env python3
"""Generate crates/wire/src/catalogue.rs from MH3SP and MHTrIDA.

Names come from MH3SP's PatID4 class (unique per id; PAT_NAMES reuses names for the
LMP- and FMP-stage server list packets and for both ticket packets); the Japanese
name and the English description come from MHTrIDA's PAT.MD (the game's own table).

Usage: tools/gen_catalogue.py [DIR] [MHTRIDA_DIR]
Defaults: ../reference and ../lab/mhtrida, relative to the repository root.
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
mh3sp = Path(sys.argv[1]) if len(sys.argv) > 1 else root.parent / "mh3sp"
mhtrida = Path(sys.argv[2]) if len(sys.argv) > 2 else mh3sp / "lab" / "mhtrida"

constants = (mh3sp / "mh" / "constants.py").read_text()
patid4 = constants[constants.index("class PatID4"):constants.index("class PatServerType")]
names = {int(i, 16): n for n, i in re.findall(r"^\s+(\w+) = 0x([0-9a-f]{8})", patid4, re.M)}
if len(set(names.values())) != len(names):
    sys.exit("PatID4 names are not unique")
docs = {
    int(i, 16): (jp.strip(), en.strip())
    for i, _, jp, en in re.findall(r"^\|([0-9A-Fa-f]{8})\|([^|]*)\|([^|]*)\|([^|]*)\|",
                                   (mhtrida / "server" / "doc" / "PAT.MD").read_text(), re.M)
}
if names.keys() != docs.keys():
    sys.exit("ID lists differ: only MH3SP {}, only MHTrIDA {}".format(
        sorted(map(hex, names.keys() - docs.keys())), sorted(map(hex, docs.keys() - names.keys()))))


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "// @generated by tools/gen_catalogue.py from MH3SP `PatID4` and MHTrIDA `server/doc/PAT.MD`.",
    "// Do not edit by hand: rerun the script.",
    "",
    "use crate::id::Entry;",
    "",
    "/// Every PAT packet id known to the game, sorted by id.",
    "#[rustfmt::skip]",
    "pub(crate) static CATALOGUE: [Entry; {}] = [".format(len(names)),
]
for i in sorted(names):
    jp, en = docs[i]
    lines.append("    Entry {{ id: 0x{:08X}, name: {}, japanese: {}, english: {} }},".format(
        i, rust_str(names[i]), rust_str(jp), rust_str(en)))
lines += ["];", ""]

out = root / "crates" / "wire" / "src" / "catalogue.rs"
out.write_text("\n".join(lines), encoding="utf-8")
print("wrote {} entries to {}".format(len(names), out.relative_to(root)))
